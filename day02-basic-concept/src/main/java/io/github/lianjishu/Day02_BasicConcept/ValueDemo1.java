package io.github.lianjishu.Day02_BasicConcept;
public class ValueDemo1{
    // public static Array str = ;
    public static void main(String[] args){
        //整数
        System.out.println("整数:");
        System.out.println(666);
        System.out.println(-1314);
        System.out.println("\n=============================\n");
        //小数
        System.out.println("小数:");
        System.out.println(3.14);
        System.out.print(-1.123);
        System.out.println("\n=============================\n");
        //布尔类型
        System.out.println("布尔类型:");
        System.out.println(true);
        System.out.println(false);
        System.out.println("\n=============================\n");
        //字符串类型
        System.out.println("字符串类型: ");
        System.out.println("我是字符串");
        System.out.println("\n=============================\n");
        //字符类型
        System.out.println("字符类型: ");
        System.out.println('夯');
        System.out.println("\n=============================\n");
    }
}